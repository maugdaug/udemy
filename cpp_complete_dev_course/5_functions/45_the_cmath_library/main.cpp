#include <iostream>
#include <cmath>        // go to cplusplus.com to see more functions in cmath


int main() {
    int powResult = pow(2, 3);
    int sqrtResult = sqrt(25);
    int ceilResult = ceil(4.2);
    int floorResult = floor(4.2);

    std::cout << powResult << std::endl;
    std::cout << sqrtResult << std::endl;
    std::cout << ceilResult << std::endl;
    std::cout << floorResult << std::endl;

    return 0;
}